    // MARK: - 收藏本機持久化 (UserDefaults)

    func getSavedFavoriteIds() -> Set<String> {
        let array = UserDefaults.standard.stringArray(forKey: favoritesKey) ?? []
        return Set(array)
    }

    func saveFavorite(id: UUID, isFavorite: Bool) {
        var current = getSavedFavoriteIds()
        if isFavorite {
            current.insert(id.uuidString)
        } else {
            current.remove(id.uuidString)
        }
        UserDefaults.standard.set(Array(current), forKey: favoritesKey)
    }

    // MARK: - 社群問題回報持久化 (Facility Reports)

    func getSavedReports() -> [FacilityReport] {
        guard let data = UserDefaults.standard.data(forKey: reportsKey) else { return [] }
        if let decoded = try? JSONDecoder().decode([FacilityReport].self, from: data) {
            return decoded
        }
        return []
    }

    func saveReport(_ report: FacilityReport) {
        var current = getSavedReports()
        current.insert(report, at: 0) // 最新回報置頂
        if let encoded = try? JSONEncoder().encode(current) {
            UserDefaults.standard.set(encoded, forKey: reportsKey)
        }
    }
