    /// 取得預設全台便民設施資料庫（優先自 App Bundle 載入官方開放資料 3,900+ 處據點，並以精選種子清單作為備援）
    func loadInitialFacilities() -> [Facility] {
        let savedFavorites = getSavedFavoriteIds()
        var items: [Facility] = []

        // 1. 嘗試從 App Bundle 或專案本機路徑載入全台開放資料 JSON
        let possibleUrls = [
            Bundle.main.url(forResource: "taiwan_facilities", withExtension: "json"),
            Bundle.main.url(forResource: "taiwan_facilities", withExtension: "json", subdirectory: "Resources"),
            Bundle.main.url(forResource: "taiwan_facilities", withExtension: "json", subdirectory: "AIapp/Resources"),
            URL(fileURLWithPath: "/Users/115-1student04/Desktop/AIapp/AIapp/Resources/taiwan_facilities.json")
        ].compactMap { $0 }

        for url in possibleUrls {
            do {
                let data = try Data(contentsOf: url)
                let decoded = try JSONDecoder().decode([Facility].self, from: data)
                if !decoded.isEmpty {
                    items = decoded
                    print("✅ 成功載入全台設施資料庫：\(items.count) 處據點 (來源: \(url.lastPathComponent))")
                    break
                }
            } catch {
                print("⚠️ 嘗試載入 \(url.lastPathComponent) 失敗: \(error)")
            }
        }

        // 2. 若極端情況下仍為空，使用內建備用種子資料庫
        if items.isEmpty {
            items = curatedSeedFacilities()
            print("⚠️ 使用內建備用種子資料庫，共 \(items.count) 處據點")
        }

        // 綁定保存的收藏狀態
        for i in 0..<items.count {
            if savedFavorites.contains(items[i].id.uuidString) {
                items[i].isFavorite = true
            }
        }

        return items
    }

